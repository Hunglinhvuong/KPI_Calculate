-- Schema PostgreSQL cho Dashboard KPI chuyên viên viễn thông (V1)
-- Chạy lại an toàn: dùng IF NOT EXISTS.
--
-- Quy ước nhận diện phường giữa các nguồn (đã được người dùng xác nhận):
--   SmartF ward_day.DISTRICT = VHKT.WARD_NAME = ward.ward_code
-- Tỉnh (PROVINCE / PROVINCE_NAME / province_name) đi kèm để phân biệt các phường trùng tên.
-- DATETIME_ID (SmartF Noc7) có dạng YYYYMMDDHH và được giữ trong khóa nguồn.

-- 1. ward: nguồn từ data/ward.csv ------------------------------------------
CREATE TABLE IF NOT EXISTS ward (
    -- IDENTITY cho phép nạp ward_id có sẵn từ CSV. Sau khi nạp cần đồng bộ sequence (giai đoạn 2).
    ward_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ward_code     TEXT NOT NULL,              -- khớp ward_day.DISTRICT và VHKT.WARD_NAME
    province_name TEXT NOT NULL,
    ward_name     TEXT NOT NULL,
    employee_code TEXT,
    employee_name TEXT,
    is_active     BOOLEAN NOT NULL DEFAULT TRUE,   -- ô trống trong CSV = TRUE (xử lý khi nạp)
    number_site   INTEGER CONSTRAINT ck_ward_number_site CHECK (number_site >= 0),  -- số trạm trong xã/phường
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_ward_province_code UNIQUE (province_name, ward_code)
);
-- Nâng cấp database đã tạo từ phiên bản schema trước (chưa có number_site). Chạy lại an toàn.
ALTER TABLE ward ADD COLUMN IF NOT EXISTS number_site INTEGER;
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_ward_number_site') THEN
        ALTER TABLE ward ADD CONSTRAINT ck_ward_number_site CHECK (number_site >= 0);
    END IF;
END $$;

-- 2. ward_day: KPI phường từ báo cáo SmartF/Playwright (theo WARD_DAY_template.csv)
CREATE TABLE IF NOT EXISTS ward_day (
    id               BIGSERIAL PRIMARY KEY,
    stt              INTEGER,
    datetime_id      BIGINT NOT NULL,          -- YYYYMMDDHH từ cột Noc7 của báo cáo Playwright
    -- Ngày và giờ suy ra từ datetime_id (lỗi nếu datetime_id sai định dạng -> chặn dữ liệu bẩn)
    data_date        DATE NOT NULL GENERATED ALWAYS AS (
                         make_date((datetime_id / 1000000)::int,
                                   ((datetime_id / 10000) % 100)::int,
                                   ((datetime_id / 100) % 100)::int)
                     ) STORED,
    data_hour        SMALLINT NOT NULL GENERATED ALWAYS AS ((datetime_id % 100)::smallint) STORED,
    province         TEXT NOT NULL,
    district         TEXT NOT NULL,            -- = ward.ward_code
    ward_id          BIGINT REFERENCES ward (ward_id),   -- NULL nếu chưa ghép được
    mtcl_2026        NUMERIC(18,6),
    danh_gia         VARCHAR(10),
    htmt_kpi         NUMERIC(18,6),
    htmt_qos         NUMERIC(18,6),
    htmt_vhkt        NUMERIC(18,6),
    htmt_anm         NUMERIC(18,6),
    traffic_all_gb  DOUBLE PRECISION,         -- SUM(TRAFFIC_ALL_GB)
    cssr             DOUBLE PRECISION,
    pasr             DOUBLE PRECISION,
    cdr              DOUBLE PRECISION,
    padr             DOUBLE PRECISION,
    hosr             DOUBLE PRECISION,
    prb_dl           DOUBLE PRECISION,
    dkd              DOUBLE PRECISION,
    badlink_4g       DOUBLE PRECISION,
    vn_cssr          DOUBLE PRECISION,
    vn_call_drop     DOUBLE PRECISION,
    mc_staon_num_r   DOUBLE PRECISION,
    usr_dl_thp_4g    DOUBLE PRECISION,
    usr_dl_thp_5g    DOUBLE PRECISION,
    rsrp             DOUBLE PRECISION,
    collected_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- Khóa nguồn: không dùng STT (chỉ là số thứ tự dòng). Dùng cho upsert.
    CONSTRAINT uq_ward_day_source UNIQUE (province, district, datetime_id)
);
-- Nâng cấp database đã tạo từ schema trước (thiếu danh_gia/htmt_anm, 4 cột còn là DOUBLE PRECISION).
-- Chạy lại an toàn: chỉ đổi kiểu khi cột chưa phải NUMERIC.
ALTER TABLE ward_day ADD COLUMN IF NOT EXISTS danh_gia VARCHAR(10);
ALTER TABLE ward_day ADD COLUMN IF NOT EXISTS htmt_anm NUMERIC(18,6);
DO $$
DECLARE col text;
BEGIN
    FOREACH col IN ARRAY ARRAY['mtcl_2026', 'htmt_kpi', 'htmt_qos', 'htmt_vhkt'] LOOP
        IF EXISTS (SELECT 1 FROM information_schema.columns
                   WHERE table_schema = current_schema() AND table_name = 'ward_day'
                     AND column_name = col AND data_type <> 'numeric') THEN
            EXECUTE format('ALTER TABLE ward_day ALTER COLUMN %I TYPE NUMERIC(18,6)', col);
        END IF;
    END LOOP;
END $$;
CREATE INDEX IF NOT EXISTS ix_ward_day_ward_date ON ward_day (ward_id, data_date);
CREATE INDEX IF NOT EXISTS ix_ward_day_date ON ward_day (data_date);

-- 3. vhkt_day: dữ liệu VHKT từ Playwright ----------------------------------
CREATE TABLE IF NOT EXISTS vhkt_day (
    id             BIGSERIAL PRIMARY KEY,
    province_name  TEXT NOT NULL,
    ward_name      TEXT NOT NULL,              -- = ward.ward_code
    ward_id        BIGINT REFERENCES ward (ward_id),   -- NULL nếu chưa ghép được
    cells7         TEXT NOT NULL,
    sdate          TIMESTAMP NOT NULL,         -- nguồn dạng dd/mm/yyyy hh:mi:ss, chuyển đổi khi nạp
    edate          TIMESTAMP,
    data_date      DATE NOT NULL GENERATED ALWAYS AS (sdate::date) STORED,  -- ngày trích từ SDATE
    minute_number  DOUBLE PRECISION,
    network        TEXT,
    ma_phong_xl    TEXT,
    ma_to_xl       TEXT,
    uu_tien        TEXT,
    dat            TEXT,
    collected_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- Chống ghi trùng (edate/network có thể NULL nên dùng COALESCE). Khóa tạm thời,
-- sẽ chốt lại ở giai đoạn 4 khi xem dữ liệu Playwright thật.
CREATE UNIQUE INDEX IF NOT EXISTS uq_vhkt_day_source ON vhkt_day (
    province_name, ward_name, cells7, sdate,
    COALESCE(edate, 'infinity'::timestamp),
    COALESCE(network, '')
);
CREATE INDEX IF NOT EXISTS ix_vhkt_day_ward_date ON vhkt_day (ward_id, data_date);
CREATE INDEX IF NOT EXISTS ix_vhkt_day_date ON vhkt_day (data_date);

-- 4. monthly_summary: KPI theo tháng và phường, lưu lịch sử -----------------
-- Công thức KPI chưa được định nghĩa nên các chỉ số lưu trong JSONB;
-- sẽ tách cột khi chốt công thức ở giai đoạn 5.
CREATE TABLE IF NOT EXISTS monthly_summary (
    month          DATE NOT NULL,              -- ngày đầu tháng
    ward_id        BIGINT NOT NULL REFERENCES ward (ward_id),
    employee_code  TEXT,                       -- chuyên viên phụ trách tại thời điểm tổng hợp
    days_with_data INTEGER,
    kpi_values     JSONB NOT NULL DEFAULT '{}'::jsonb,
    is_final       BOOLEAN NOT NULL DEFAULT FALSE,
    computed_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (month, ward_id),
    CONSTRAINT ck_monthly_summary_month CHECK (month = date_trunc('month', month)::date)
);
